// Usage: node scripts/gen_ts_contracts.mjs <bundle.json> <out-dir>
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { compile } from "json-schema-to-typescript";

const [bundlePath, outDir] = process.argv.slice(2);
const bundle = JSON.parse(readFileSync(bundlePath, "utf8"));
const ts = await compile(bundle, "Contracts", {
  bannerComment: "/* Generated by `make contracts` from contracts/schemas. Never hand-edit. */",
  additionalProperties: false,
  unreachableDefinitions: true,
  format: false,
});
mkdirSync(outDir, { recursive: true });
writeFileSync(`${outDir}/index.ts`, ts);
