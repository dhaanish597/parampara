// Generates packages/contracts/src/openapi/paths.d.ts from the API's OpenAPI document (BUILD_PLAN 8, T-012 AC3).
// Usage: API_BASE=http://localhost:8000 pnpm --filter @parampara/web gen:api
import { writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";

const base = process.env.API_BASE ?? "http://localhost:8000";
const ast = await openapiTS(new URL("/openapi.json", base));
const banner = "// Generated by scripts/gen-api.mjs from the API OpenAPI document. Do not edit.\n";
await writeFile(new URL("../../../packages/contracts/src/openapi/paths.d.ts", import.meta.url), banner + astToString(ast));
console.log(`packages/contracts/src/openapi/paths.d.ts written from ${base}/openapi.json`);
